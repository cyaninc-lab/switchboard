import java.util.Properties
import org.jetbrains.kotlin.gradle.dsl.JvmTarget

plugins {
    id("com.android.application")
    id("org.jetbrains.kotlin.android")
    id("rust")
}

val tauriProperties = Properties().apply {
    val propFile = file("tauri.properties")
    if (propFile.exists()) {
        propFile.inputStream().use { load(it) }
    }
}

android {
    compileSdk = 37
    namespace = "org.cyaninc.switchboard"
    defaultConfig {
        // daemons are reached over plain http on the user's tailnet (Tailscale encrypts it; the daemon has no TLS yet)
        manifestPlaceholders["usesCleartextTraffic"] = "true"
        applicationId = "org.cyaninc.switchboard"
        minSdk = 24
        targetSdk = 37
        versionCode = tauriProperties.getProperty("tauri.android.versionCode", "1").toInt()
        versionName = tauriProperties.getProperty("tauri.android.versionName", "1.0")
    }
    // release signing: CI writes the key from repo secrets; locally it lives in ~/.config/switchboard-android (backup: Bitwarden).
    // Every update must be signed with this same key or Android refuses to install it over the old one.
    val keyDir = System.getenv("SWITCHBOARD_ANDROID_KEYS") ?: "${System.getProperty("user.home")}/.config/switchboard-android"
    val keyFile = file("$keyDir/release.jks")
    signingConfigs {
        if (keyFile.exists()) create("release") {
            storeFile = keyFile
            storePassword = file("$keyDir/password").readText().trim()
            keyAlias = "switchboard"
            keyPassword = storePassword
        }
    }
    buildTypes {
        getByName("debug") {
            manifestPlaceholders["usesCleartextTraffic"] = "true"
            isDebuggable = true
            isJniDebuggable = true
            isMinifyEnabled = false
            packaging {
                jniLibs.keepDebugSymbols.add("*/arm64-v8a/*.so")
                jniLibs.keepDebugSymbols.add("*/armeabi-v7a/*.so")
                jniLibs.keepDebugSymbols.add("*/x86/*.so")
                jniLibs.keepDebugSymbols.add("*/x86_64/*.so")
            }
        }
        getByName("release") {
            signingConfigs.findByName("release")?.let { signingConfig = it }
            optimization {
               enable = true
            }
            proguardFiles(
                *fileTree(".") {
                  include("**/*.pro")
                  exclude("build/**")
                }.files.toTypedArray()
            )
        }
    }
    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_1_8
        targetCompatibility = JavaVersion.VERSION_1_8
    }
    buildFeatures {
        buildConfig = true
    }
}

kotlin {
    compilerOptions {
        jvmTarget = JvmTarget.JVM_1_8
    }
}

